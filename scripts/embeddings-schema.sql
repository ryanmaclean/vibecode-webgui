-- Create a view for embedding statistics
CREATE OR REPLACE VIEW embedding_stats AS
SELECT 
  date_trunc('hour', created_at) AS hour_bucket,
  COUNT(*) AS total_embeddings,
  AVG(LENGTH(content)) AS avg_content_length,
  COUNT(DISTINCT document_id) AS unique_documents,
  'azure' AS provider
FROM 
  embeddings
GROUP BY 
  hour_bucket
ORDER BY 
  hour_bucket DESC;

-- Create a function to cleanup old embeddings (optional)
CREATE OR REPLACE FUNCTION cleanup_old_embeddings(age_in_days INTEGER DEFAULT 30)
RETURNS INTEGER AS $$
DECLARE
  deleted_count INTEGER;
BEGIN
  DELETE FROM embeddings
  WHERE updated_at < NOW() - (age_in_days * INTERVAL '1 day')
  RETURNING COUNT(*) INTO deleted_count;
  
  RETURN deleted_count;
END;
$$ LANGUAGE plpgsql;

-- Add a comment to the embeddings table
COMMENT ON TABLE embeddings IS 'Stores document embeddings generated by Azure OpenAI';

